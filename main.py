def report(name, exc):
    """Show a failure on the REPL (never raises)."""
    try:
        print('ERROR in', name)
        sys.print_exception(exc)
    except Exception:
        pass


def fatal(reason):
    print('FATAL:', reason, '- resetting')
    utime.sleep_ms(200)
    machine.reset()


# Key handling: the pin IRQs only debounce, classify and queue; the main loop does the work
events = nav.EventQueue(8)
navigator = nav.Navigator(nav.PAGES if WIFI_ENABLE else tuple(p for p in nav.PAGES if p != nav.PAGE_WIFI))


def make_button_handler(tracker):
    def handler(pin):
        ev = tracker.edge(pin.value(), utime.ticks_ms())
        if ev:
            events.put(ev)
    return handler

key0 = Pin(PIN_KEY_UP, Pin.IN, Pin.PULL_UP)
key1 = Pin(PIN_KEY_DN, Pin.IN, Pin.PULL_UP)
# Register the handler functions for both rising and falling edges
key0.irq(trigger=Pin.IRQ_FALLING | Pin.IRQ_RISING, handler=make_button_handler(
    nav.ButtonTracker('UP', LONG_PRESS_THRESHOLD, WIFI_TOGGLE_PRESS if WIFI_ENABLE else None)))
key1.irq(trigger=Pin.IRQ_FALLING | Pin.IRQ_RISING, handler=make_button_handler(
    nav.ButtonTracker('DN', LONG_PRESS_THRESHOLD)))

# Radio path
nmea_parser = NMEA.Parser()
rx_queue = RxQueue(16, _thread.allocate_lock())
radio = UART(RS485_UART, baudrate=RS485_BAUDRATE, tx=Pin(RS485_TX), rx=Pin(RS485_RX), txbuf=RS485_TXBUF)
radio.init(RS485_BAUDRATE, bits=8, parity=None, stop=1)
