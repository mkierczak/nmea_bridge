# Wi-Fi (Pico W): imported and started only when switched on
wifi_ssid = wifi_password = ''
if WIFI_ENABLE:
    wifi_ssid = wificreds.get_ssid(WIFI_SSID)
    wifi_password, wifi_pw_stored = wificreds.get_password(WIFI_PASSWORD)
    if WIFI_PASSWORD and wifi_password != WIFI_PASSWORD:
        print('WARNING: WIFI_PASSWORD must have 8-63 printable ASCII characters; using a generated one')
    if DEBUG and not wifi_pw_stored:
        print('WARNING: could not store the Wi-Fi password; it changes at every boot')
wdt = None                        # armed on the first valid GPS sentence (can't be stopped once started)


def set_wifi(on):
    """Start/stop the access point. wifi.py is imported lazily so the default footprint stays small."""
    if on:
        if core.broadcaster is None:
            import network
            import socket
            import wifi
            core.broadcaster = wifi.NmeaBroadcaster(network, socket, wifi_ssid, wifi_password,
                                                    WIFI_PORT, WIFI_MAX_CLIENTS, WIFI_COUNTRY, WIFI_CHANNEL)
        gc.collect()
        try:
            core.broadcaster.start(feed=wdt.feed if wdt else None, sleep_ms=utime.sleep_ms)
        except Exception as e:  # bad password, AP did not come up, ...
            print('Wi-Fi start failed:', e)
        gc.collect()
    elif core.broadcaster:
        core.broadcaster.stop()
        gc.collect()


def wifi_active():
    return bool(core.broadcaster and core.broadcaster.active)


def wifi_info():
    state, ssid, ip, clients, max_clients = (core.broadcaster.info() if core.broadcaster
                                             else ('OFF', wifi_ssid, '', 0, WIFI_MAX_CLIENTS))
    return state, ssid, ip, clients, max_clients, wifi_password


def memreport(tag):
    gc.collect()
    print('MEM {}: free {} B, used {} B'.format(tag, gc.mem_free(), gc.mem_alloc()))


def make_spoof():
    # GPS time check must tolerate how late a sentence can arrive behind a big GSA/GSV cycle
    return SpoofDetector(nmea_parser,
                         spoofing.TIME_JUMP_MS + l76x.nmea_burst_ms(GPS_BAUDRATE, GNSS_MODE == 'GPS+BD'))


def apply_setting(key):
    """Make a changed live setting take effect (called by the menu)."""
    if key == 'jam_detect':
        core.detector = JamDetector(nmea_parser) if cfg.get(key) else None
    elif key == 'spoof_detect':
        core.spoof = make_spoof() if cfg.get(key) else None
    elif key == 'spoof_action':
        core.spoof_action = cfg.get(key)
    elif key.startswith('fwd_'):
        core.forward_types = tuple(t for t in FORWARD_TYPES_ALL if cfg.get('fwd_' + t))
    elif key == 'contrast':
        oled.contrast(cfg.get(key))
    elif key == 'log_raw':
        set_raw_log(cfg.get(key))
    elif key != 'screen_off_s':   # read every loop; everything else is an advanced threshold
        settings.apply_thresholds(cfg, jamming, spoofing)
        if core.spoof:
            core.spoof.time_tolerance_ms = (spoofing.TIME_JUMP_MS +
                                            l76x.nmea_burst_ms(GPS_BAUDRATE, GNSS_MODE == 'GPS+BD'))


def reset_settings():
    before = dict(cfg.values)
    cfg.reset()
    for key, value in cfg.values.items():
        if value != before[key] and settings.spec(key)[4] == settings.LIVE:
            apply_setting(key)


def regenerate_wifi_password():
    global wifi_password
    if WIFI_PASSWORD:
        print('WIFI_PASSWORD is set in main.py: nothing to regenerate')
        return
    wifi_password, _ = wificreds.regenerate_password()
    if core.broadcaster:
        was_on = core.broadcaster.active
        core.broadcaster.set_password(wifi_password)
        if was_on:  # restart so the new password is in use
            set_wifi(False)
            set_wifi(True)


menu_hooks = {'apply': apply_setting, 'reset': reset_settings, 'reboot': machine.reset}
if WIFI_ENABLE:
    menu_hooks['wifi_active'] = wifi_active
    menu_hooks['wifi_toggle'] = lambda: set_wifi(not wifi_active())
    menu_hooks['regen_password'] = regenerate_wifi_password


def make_menu():
    import menu as menu_mod   # imported only while the menu is open
    return menu_mod.Menu(cfg, menu_hooks)


_heap = [0, None]   # ticks of last reading, free bytes


def free_heap(now_ms):
    """Free heap after a collection (a raw reading swings with the uncollected garbage), refreshed every
    HEAP_REFRESH_MS and rounded down to 4 KiB so it does not force screen redraws."""
    if _heap[1] is None or utime.ticks_diff(now_ms, _heap[0]) >= HEAP_REFRESH_MS:
        gc.collect()
        _heap[0], _heap[1] = now_ms, gc.mem_free() // 4096 * 4096
    return _heap[1]


def system_info():
    inv_base = core.stats['rcv'] or 1
    return {'uptime_s': screen_ui.uptime_ms // 1000, 'heap': free_heap(utime.ticks_ms()),
            'dropped': rx_queue.dropped, 'inv_pct': round(core.stats['inv'] * 100 / inv_base),
            'baud': GPS_BAUDRATE, 'found': reader.found, 'fix_ms': FIX_INTERVAL_MS, 'gnss': GNSS_MODE,
            'uid': binascii.hexlify(machine.unique_id()).decode(), 'now_ms': utime.ticks_ms(),
            'version': VERSION}


core.detector = JamDetector(nmea_parser) if cfg.get('jam_detect') else None
core.spoof = make_spoof() if cfg.get('spoof_detect') else None
screen_ui = ui.UiController(cfg, oled, font_large, screens.draw, navigator, events, core, make_menu,
                            wifi_info, system_info, lambda: set_wifi(not wifi_active()), utime.ticks_ms,
                            menu_timeout_ms=60 * 1000)

utime.sleep(1)  # grace time for the UARTs to start
last_mem_report = utime.ticks_ms()
if DEBUG:
    memreport('boot')

# Main loop. The radio path and the UI are separate: a failure in one must not stop the other, and the
# watchdog is handled outside both.
while True:
    now = utime.ticks_ms()
    try:
        core.step(now)
    except Exception as e:  # core.step contains its own failures; this is the last line of defence
        report('bridge', e)
    try:
        screen_ui.step(now)
    except Exception as e:
        report('ui', e)

    if core.watchdog.should_arm():
        wdt = WDT(timeout=WATCHDOG_TIMEOUT)
        core.watchdog.armed = True
    if wdt and core.watchdog.should_feed(now):
        wdt.feed()

    if DEBUG and utime.ticks_diff(now, last_mem_report) > MEM_REPORT_PERIOD:
        memreport('run')
        last_mem_report = now

    utime.sleep(0.01)  # yield so the GPS thread isn't starved
